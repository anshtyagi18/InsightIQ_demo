"""
Export service for dashboard PDF, PNG, and HTML generation.
Supports role-based access controls and various export formats.
"""

import asyncio
import base64
import json
import os
import tempfile
import uuid
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Dict, Any, List, Optional, Union
import logging

from fastapi import HTTPException
from jinja2 import Environment, FileSystemLoader, Template
from playwright.async_api import async_playwright, Page, Browser
from pydantic import BaseModel, Field

logger = logging.getLogger(__name__)

class ExportFormat(str, Enum):
    """Supported export formats."""
    PDF = "pdf"
    PNG = "png"
    HTML = "html"
    SVG = "svg"

class ExportOptions(BaseModel):
    """Export configuration options."""
    format: ExportFormat = Field(..., description="Export format")
    width: int = Field(1200, description="Viewport width in pixels")
    height: int = Field(800, description="Viewport height in pixels")
    scale: float = Field(1.0, description="Scale factor for output")
    full_page: bool = Field(True, description="Capture full page")
    wait_for: Optional[str] = Field(None, description="Selector to wait for before export")
    timeout: int = Field(30000, description="Timeout in milliseconds")
    background: bool = Field(True, description="Include background graphics")
    margin: Dict[str, str] = Field(
        default_factory=lambda: {"top": "1cm", "right": "1cm", "bottom": "1cm", "left": "1cm"},
        description="Page margins for PDF"
    )

class ExportResult(BaseModel):
    """Export operation result."""
    export_id: str = Field(..., description="Unique export identifier")
    format: ExportFormat = Field(..., description="Export format")
    file_path: Optional[str] = Field(None, description="Path to exported file")
    file_data: Optional[bytes] = Field(None, description="Binary file data")
    file_size: int = Field(0, description="File size in bytes")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Export metadata")
    created_at: datetime = Field(default_factory=datetime.now, description="Creation timestamp")
    user_id: Optional[str] = Field(None, description="User who created the export")

class DashboardExportService:
    """Service for exporting dashboards to various formats."""
    
    def __init__(self, template_dir: str = "templates", output_dir: str = "exports"):
        """Initialize export service."""
        self.template_dir = Path(template_dir)
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(exist_ok=True)
        
        # Initialize Jinja2 environment
        self.jinja_env = Environment(
            loader=FileSystemLoader(str(self.template_dir)),
            autoescape=True
        )
        
        # Store active browser instance
        self._browser: Optional[Browser] = None
        
    async def _get_browser(self) -> Browser:
        """Get or create browser instance."""
        if self._browser is None or not self._browser.is_connected():
            playwright = await async_playwright().start()
            self._browser = await playwright.chromium.launch(
                headless=True,
                args=['--no-sandbox', '--disable-setuid-sandbox']
            )
        return self._browser
    
    async def close(self):
        """Close browser instance."""
        if self._browser and self._browser.is_connected():
            await self._browser.close()
            self._browser = None
    
    def _generate_export_id(self) -> str:
        """Generate unique export identifier."""
        return f"export_{uuid.uuid4().hex[:12]}_{int(datetime.now().timestamp())}"
    
    def _prepare_dashboard_data(self, dashboard_data: Dict[str, Any]) -> Dict[str, Any]:
        """Prepare dashboard data for template rendering."""
        # Add default metadata and styling
        prepared_data = {
            "dashboard": dashboard_data,
            "export_timestamp": datetime.now().isoformat(),
            "export_id": self._generate_export_id(),
            "charts": dashboard_data.get("charts", []),
            "kpis": dashboard_data.get("kpis", []),
            "layout": dashboard_data.get("layout", {}),
            "theme": dashboard_data.get("theme", "default"),
            "title": dashboard_data.get("title", "Dashboard Export"),
            "description": dashboard_data.get("description", "Generated by Analytics Hub")
        }
        
        # Add chart.js CDN and styling
        prepared_data["chart_js_cdn"] = "https://cdn.jsdelivr.net/npm/chart.js"
        prepared_data["bootstrap_cdn"] = "https://cdn.jsdelivr.net/npm/bootstrap@5.1.3/dist/css/bootstrap.min.css"
        
        return prepared_data
    
    async def export_dashboard_html(
        self, 
        dashboard_data: Dict[str, Any],
        template_name: str = "dashboard_export.html",
        options: Optional[ExportOptions] = None
    ) -> ExportResult:
        """Export dashboard as HTML file."""
        try:
            export_id = self._generate_export_id()
            
            # Prepare data for template
            template_data = self._prepare_dashboard_data(dashboard_data)
            template_data["export_id"] = export_id
            
            # Load and render template
            template = self.jinja_env.get_template(template_name)
            html_content = template.render(**template_data)
            
            # Save HTML file
            output_path = self.output_dir / f"{export_id}.html"
            with open(output_path, 'w', encoding='utf-8') as f:
                f.write(html_content)
            
            return ExportResult(
                export_id=export_id,
                format=ExportFormat.HTML,
                file_path=str(output_path),
                file_data=html_content.encode('utf-8'),
                file_size=len(html_content.encode('utf-8')),
                metadata={
                    "template_used": template_name,
                    "dashboard_title": template_data.get("title", "Unknown"),
                    "chart_count": len(template_data.get("charts", [])),
                    "kpi_count": len(template_data.get("kpis", []))
                }
            )
            
        except Exception as e:
            logger.error(f"HTML export failed: {str(e)}")
            raise HTTPException(status_code=500, detail=f"HTML export failed: {str(e)}")
    
    async def export_dashboard_pdf(
        self, 
        dashboard_data: Dict[str, Any],
        options: Optional[ExportOptions] = None
    ) -> ExportResult:
        """Export dashboard as PDF file."""
        try:
            if options is None:
                options = ExportOptions(format=ExportFormat.PDF)
            
            export_id = self._generate_export_id()
            
            # First generate HTML
            html_result = await self.export_dashboard_html(dashboard_data)
            
            # Launch browser and create PDF
            browser = await self._get_browser()
            page = await browser.new_page()
            
            try:
                # Set viewport
                await page.set_viewport_size({"width": options.width, "height": options.height})
                
                # Navigate to HTML file
                await page.goto(f"file://{Path(html_result.file_path).resolve()}")
                
                # Wait for content to load
                if options.wait_for:
                    await page.wait_for_selector(options.wait_for, timeout=options.timeout)
                else:
                    await page.wait_for_load_state("networkidle", timeout=options.timeout)
                
                # Generate PDF
                pdf_path = self.output_dir / f"{export_id}.pdf"
                pdf_data = await page.pdf(
                    path=str(pdf_path),
                    format="A4",
                    print_background=options.background,
                    margin=options.margin,
                    prefer_css_page_size=True
                )
                
                return ExportResult(
                    export_id=export_id,
                    format=ExportFormat.PDF,
                    file_path=str(pdf_path),
                    file_data=pdf_data,
                    file_size=len(pdf_data),
                    metadata={
                        "dashboard_title": dashboard_data.get("title", "Unknown"),
                        "page_size": "A4",
                        "with_background": options.background,
                        "viewport": f"{options.width}x{options.height}"
                    }
                )
                
            finally:
                await page.close()
                
        except Exception as e:
            logger.error(f"PDF export failed: {str(e)}")
            raise HTTPException(status_code=500, detail=f"PDF export failed: {str(e)}")
    
    async def export_dashboard_png(
        self, 
        dashboard_data: Dict[str, Any],
        options: Optional[ExportOptions] = None
    ) -> ExportResult:
        """Export dashboard as PNG image."""
        try:
            if options is None:
                options = ExportOptions(format=ExportFormat.PNG)
            
            export_id = self._generate_export_id()
            
            # First generate HTML
            html_result = await self.export_dashboard_html(dashboard_data)
            
            # Launch browser and create screenshot
            browser = await self._get_browser()
            page = await browser.new_page()
            
            try:
                # Set viewport
                await page.set_viewport_size({"width": options.width, "height": options.height})
                
                # Navigate to HTML file
                await page.goto(f"file://{Path(html_result.file_path).resolve()}")
                
                # Wait for content to load
                if options.wait_for:
                    await page.wait_for_selector(options.wait_for, timeout=options.timeout)
                else:
                    await page.wait_for_load_state("networkidle", timeout=options.timeout)
                
                # Take screenshot
                png_path = self.output_dir / f"{export_id}.png"
                png_data = await page.screenshot(
                    path=str(png_path),
                    full_page=options.full_page,
                    scale="device" if options.scale == 1.0 else "css"
                )
                
                return ExportResult(
                    export_id=export_id,
                    format=ExportFormat.PNG,
                    file_path=str(png_path),
                    file_data=png_data,
                    file_size=len(png_data),
                    metadata={
                        "dashboard_title": dashboard_data.get("title", "Unknown"),
                        "full_page": options.full_page,
                        "viewport": f"{options.width}x{options.height}",
                        "scale": options.scale
                    }
                )
                
            finally:
                await page.close()
                
        except Exception as e:
            logger.error(f"PNG export failed: {str(e)}")
            raise HTTPException(status_code=500, detail=f"PNG export failed: {str(e)}")
    
    async def export_dashboard(
        self, 
        dashboard_data: Dict[str, Any],
        format: ExportFormat,
        options: Optional[ExportOptions] = None,
        user_id: Optional[str] = None
    ) -> ExportResult:
        """Export dashboard in specified format."""
        try:
            logger.info(f"Starting dashboard export in {format} format for user {user_id}")
            
            if format == ExportFormat.HTML:
                result = await self.export_dashboard_html(dashboard_data, options=options)
            elif format == ExportFormat.PDF:
                result = await self.export_dashboard_pdf(dashboard_data, options=options)
            elif format == ExportFormat.PNG:
                result = await self.export_dashboard_png(dashboard_data, options=options)
            else:
                raise HTTPException(status_code=400, detail=f"Unsupported export format: {format}")
            
            # Add user information
            result.user_id = user_id
            result.metadata["export_format"] = format
            result.metadata["export_timestamp"] = datetime.now().isoformat()
            
            logger.info(f"Export completed successfully: {result.export_id}")
            return result
            
        except Exception as e:
            logger.error(f"Dashboard export failed: {str(e)}")
            raise HTTPException(status_code=500, detail=f"Dashboard export failed: {str(e)}")
    
    def cleanup_old_exports(self, max_age_hours: int = 24):
        """Clean up old export files."""
        try:
            cutoff_time = datetime.now().timestamp() - (max_age_hours * 3600)
            
            for file_path in self.output_dir.glob("export_*"):
                if file_path.stat().st_mtime < cutoff_time:
                    file_path.unlink()
                    logger.info(f"Cleaned up old export file: {file_path}")
                    
        except Exception as e:
            logger.error(f"Export cleanup failed: {str(e)}")

# Global export service instance
export_service = DashboardExportService() 